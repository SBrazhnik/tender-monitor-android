def assign_section(direction: str, kind: str, grp: str, value: str) -> str:
    """Раздел для признака стандартного словаря. '' — для исключений и неизвестных направлений."""
    if kind == "exclude" or direction not in SECTIONS:
        return ""
    default = _KW_DEFAULT.get(direction, SECTIONS[direction][0][0])
    if kind == "vendor":
        if direction == "IT" and grp.startswith("Серверы и ПК"):
            return "Компьютеры и комплектующие" if _PC_ALIASES.search(value) else "Серверы, СХД и ЦОД"
        for sec, groups in _VENDOR.get(direction, {}).items():
            if grp in groups:
                return sec
        return SECTIONS[direction][0][0] if direction == "ASUTP" else default
    if kind == "okpd":
        for pref, sec in _OKPD.get(direction, []):
            if value == pref or value.startswith(pref + ".") or value.startswith(pref):
                return sec
        return default
    if direction == "IT" and value.startswith("re:") and "ПО" in value:
        return "ПО и лицензии"
    v = value[3:] if value.startswith("re:") else value
    v = v.lower().replace("ё", "е")
    for sec, rx in _KW.get(direction, []):
        if re.search(rx, v):
            return sec
    return default
